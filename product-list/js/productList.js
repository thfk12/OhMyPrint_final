// URL 파라미터 가져오는 함수
function getUrlParameter(name) {
  name = name.replace(/[\[]/, '\\[').replace(/[\]]/, '\\]');
  const regex = new RegExp('[\\?&]' + name + '=([^&#]*)');
  const results = regex.exec(location.search);
  return results === null ? '' : decodeURIComponent(results[1].replace(/\+/g, ' '));
}

// 상품 표시하는 함수 (기존 로직을 함수로 분리)
function displayProducts(category) {
  const filteredProducts = productList.filter((product) => product.카테고리 === category);
  console.log(filteredProducts);

  cardWrap.innerHTML = '';

  filteredProducts.forEach((item, i, index) => {
    let pdImg = item.이미지;
    let pdName = item.상품명;
    let pdPrice = item.가격.toLocaleString('ko-KR');
    let pdBadge = item.배찌;

    cardWrap.insertAdjacentHTML(
      'beforeend',
      `
    <div class="card">
      <a href="../../product-info/productInfo.html">
        <div class="img-box">
          <img src="${pdImg}" />
        </div>
      
        <div class="item-title">
          <p class="card-title font20">${pdName}</p>
          <p class="price">
            <strong class="font20b">${pdPrice}</strong>
            <span class="font16">원</span>
          </p>
            <div class="badge-wrap">
          </div>
        </div>
      </a>
    </div>
    `
    );
    const currentCard = cardWrap.lastElementChild;
    const badgeWrap = currentCard.querySelector('.badge-wrap');

    pdBadge.forEach((badge) => {
      badgeWrap.insertAdjacentHTML('beforeend', `<span class="font14 ${badge}"></span>`);
    });
  });
}

// 웹 페이지에 카테고리(예: 명함, 간판, 현수막) 를 클릭하면,
// 그 카테고리에 맞는 상품들만 보여주는 코드예요.
// 또한 주소(URL) 에 선택한 카테고리를 저장해서
// 페이지를 다시 열어도 그 카테고리의 상품이 자동으로 보이게 해줘요.
const categoryNav = document.querySelectorAll('.main-category > li');
const cardWrap = document.querySelector('.card-wrap');

// 페이지가 처음 열릴때, 주소창에 카테고리정보가 있는지 확인(ex.?category=간판)
document.addEventListener('DOMContentLoaded', () => {
  const categoryFromUrl = getUrlParameter('category');

  //만일 카테고리 정보가 있다면
  if (categoryFromUrl) {
    // categoryNav의 li을 전부 active를 제거하고
    categoryNav.forEach((item) => {
      item.classList.remove('active');
      // URL에 있는 카테고리만 선택된 상태로 만들기
      if (item.textContent.trim() === categoryFromUrl) {
        item.classList.add('active');
      }
    });

    // displayProducts로 리스트 만들기
    displayProducts(categoryFromUrl);
  } else {
    // URL 파라미터가 없으면 HTML active 클래스가 있는 카테고리의 상품 표시
    const activeCategory = document.querySelector('.main-category > li.active');
    if (activeCategory) {
      const defaultCategory = activeCategory.textContent.trim();
      displayProducts(defaultCategory);
    }
  }
});

categoryNav.forEach((item) => {
  item.addEventListener('click', () => {
    console.log('클릭오시고');

    categoryNav.forEach((j, i) => {
      j.classList.remove('active');
      console.log('지웠고');
    });

    item.classList.add('active');

    let dataCategory = item.textContent.trim();
    console.log(dataCategory);

    // URL 업데이트 (브라우저 주소창 변경, 페이지 새로고침은 없음)
    const newUrl = new URL(window.location);
    newUrl.searchParams.set('category', dataCategory);
    window.history.pushState({}, '', newUrl);

    displayProducts(dataCategory);
  });
});

